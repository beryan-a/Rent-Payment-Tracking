    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // ADD operation
        try {
            String address = txtAddress.getText();
            String status = cmbxStatus.getSelectedItem().toString();

            if (address.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Address cannot be empty!");
                return;
            }

            Apartment apartment = new Apartment(0, currentAdminId, address, status);

            apartmentDAO.addApartment(apartment);

            loadApartmentsToTable();

            txtAptId.setText("");
            txtAddress.setText("");
            cmbxStatus.setSelectedIndex(0);

            JOptionPane.showMessageDialog(this, "Apartment added successfully!");

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Invalid input!");
        }
        
    }//GEN-LAST:event_btnAddActionPerformed

