    private void loadApartmentsToTable() {
        dtm.setRowCount(0);

        ArrayList<Apartment> apartments = apartmentDAO.loadApartments(currentAdminId);

        for (Apartment a : apartments) {
            dtm.addRow(new Object[]{
                a.getAptId(),
                a.getAdminId(),
                a.getAddress(),
                a.getStatus()
            });
        }
    }

